import { Cog, Sparkles } from "lucide-react";
import { cn } from "@/lib/utils";
import { REASON_LABEL, type AiResult } from "./use-ai";

/** Labels the origin of a suggestion (spec §B.22: fallback must be clearly stated). */
export function AiSourceBadge({ result, className }: { result: Pick<AiResult<unknown>, "source" | "reason" | "remaining">; className?: string }) {
  const ai = result.source === "ai";
  return (
    <div className={cn("flex flex-wrap items-center gap-2 text-xs", className)}>
      <span
        className={cn(
          "inline-flex items-center gap-1 rounded-full border px-2 py-0.5 font-medium",
          ai ? "border-ai/50 text-ai-text" : "border-border text-muted-foreground",
        )}
      >
        {ai ? <Sparkles className="size-3" aria-hidden /> : <Cog className="size-3" aria-hidden />}
        {ai ? "AI" : "Rules-based"}
      </span>
      {!ai && result.reason ? <span className="text-muted-foreground">Generated by rules — {REASON_LABEL[result.reason] ?? "AI unavailable"}</span> : null}
      {result.remaining ? (
        <span className="text-muted-foreground">
          {result.remaining.user} of 20 AI requests left today
        </span>
      ) : null}
    </div>
  );
}
